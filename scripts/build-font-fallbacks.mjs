// Regenerates src/styles/font-fallbacks.css.
//
//   node scripts/build-font-fallbacks.mjs
//
// The fallback faces are metric-matched stand-ins: while the web font is not
// showing, text is laid out in a local font scaled so it occupies the same
// space, and nothing moves when the web font takes over. The overrides are
// computed by capsize from both fonts' real metrics rather than measured by
// hand, so they can be regenerated rather than trusted.
//
// Two stand-ins per web font, because which local fonts exist depends on the
// platform: Windows and macOS have Arial and Georgia, Android and most Linux
// have Roboto and Noto Serif. A stand-in naming a font the visitor does not
// have is skipped, so both are listed and the first that resolves is used.

import { writeFileSync } from "node:fs";
import { createFontStack } from "@capsizecss/core";
import sourceSans3 from "@capsizecss/metrics/sourceSans3";
import arial from "@capsizecss/metrics/arial";
import roboto from "@capsizecss/metrics/roboto";
import lora from "@capsizecss/metrics/lora";
import georgia from "@capsizecss/metrics/georgia";
import notoSerif from "@capsizecss/metrics/notoSerif";

const sans = createFontStack([sourceSans3, arial, roboto]);
const serif = createFontStack([lora, georgia, notoSerif]);

const css = `/*
 * GENERATED by scripts/build-font-fallbacks.mjs. Do not edit by hand.
 *
 * Metric-matched stand-ins for the two web fonts, one per local font the
 * visitor might have. Without them the fallback text is a different width and
 * height, so every block re-wraps and moves when the web font arrives.
 */
${sans.fontFaces}
${serif.fontFaces}
`;

const out = new URL("../src/styles/font-fallbacks.css", import.meta.url);
writeFileSync(out, css);

console.log(`wrote ${out.pathname}\n`);
console.log("tailwind.config.mjs font stacks:\n");
console.log(`  sans:  ${sans.fontFamily}, sans-serif`);
console.log(`  serif: ${serif.fontFamily}, serif`);
